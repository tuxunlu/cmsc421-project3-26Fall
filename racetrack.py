import numpy as np
from utils import angle_bw

CELL = 10            # the occupancy grid has 10 x 10 cells
NX, NY = 140, 80     # grid size (the world is 1400 x 800)


def load_racetrack(fname):
    return RaceTrack(fname)


class Contour:
    def __init__(self, points):
        self.points = [np.asarray(p, dtype=float) for p in points]


class Horizontals:
    def __init__(self, horizontals):
        self.horizontals = [np.asarray(h, dtype=float) for h in horizontals]


class RaceTrack:
    def __init__(self, fname="data/racetrack.npz"):
        d = np.load(fname)
        self.occupancy = d["occupancy"].astype(int)
        self.contour_inner = Contour(d["contour_inner"])
        self.contour_outer = Contour(d["contour_outer"])
        self.racing_line = Contour(d["racing_line"])
        self.horizontals = Horizontals(d["horizontals"])
        self.finish_zone = d["finish_zone"]
        self.checkpoints = [tuple(c) for c in d["checkpoints"]]
        self._free_runs()

    def _free_runs(self):
        """runs[d][i, j] = number of free cells next to cell (i, j) in direction d before a wall or the edge."""
        free = self.occupancy == 0
        up = np.zeros((NX, NY), dtype=int)
        down = np.zeros((NX, NY), dtype=int)
        left = np.zeros((NX, NY), dtype=int)
        right = np.zeros((NX, NY), dtype=int)
        for j in range(1, NY):
            up[:, j] = np.where(free[:, j - 1], up[:, j - 1] + 1, 0)
        for j in range(NY - 2, -1, -1):
            down[:, j] = np.where(free[:, j + 1], down[:, j + 1] + 1, 0)
        for i in range(1, NX):
            left[i, :] = np.where(free[i - 1, :], left[i - 1, :] + 1, 0)
        for i in range(NX - 2, -1, -1):
            right[i, :] = np.where(free[i + 1, :], right[i + 1, :] + 1, 0)
        self.runs = (up.tolist(), down.tolist(), left.tolist(), right.tolist())
        self.free = free.tolist()

    def read_distances(self, x, y, max_sensor_range, noisy=False, std=0.0, noise_dist="gaussian", bound=5.0,
                       fail_prob=0.0):
        """
        Reads distances to walls from a given position, in 4 cardinal directions (up,down,left,right)
        x: x-coordinate of position
        y: y-coordinate of position
        max_sensor_range: maximum distance that can be read in each of the 4 directions
        noisy: specify whether the readings will be noisy, i.e. add noise to each of the distance measurements
        std: standard deviation of the noise when noise_dist is "gaussian"
        noise_dist: "gaussian" (noise N(0, std^2)) or "uniform" (noise uniform on [-bound, bound])
        fail_prob: probability that a reading is replaced by a random value, uniform on [0, max_sensor_range]
        returns numpy array of distances [up,down,left,right], of shape (4,)
        A position inside a wall or outside the map reads 0 in every direction.
        """
        if not (0 <= x < NX * CELL and 0 <= y < NY * CELL):
            return np.zeros(4)
        i = int(x // CELL)
        j = int(y // CELL)
        if not self.free[i][j]:
            return np.zeros(4)
        fx = x - CELL * i
        fy = y - CELL * j
        up, down, left, right = self.runs
        readings = np.array([fy + CELL * up[i][j], CELL - fy + CELL * down[i][j],
                             fx + CELL * left[i][j], CELL - fx + CELL * right[i][j]])
        readings = np.minimum(readings, max_sensor_range)
        if noisy:
            if noise_dist == "gaussian":
                readings = readings + np.random.normal(0, std, 4)
            elif noise_dist == "uniform":
                readings = readings + np.random.uniform(-bound, bound, 4)
            else:
                raise ValueError("unknown noise_dist {}".format(noise_dist))
            if fail_prob > 0:
                fails = np.random.uniform(0, 1, 4) < fail_prob
                readings = np.where(fails, np.random.uniform(0, max_sensor_range, 4), readings)
        return readings

    def progress(self, car):
        """Progress of a car along the lap, measured with the track cross-sections (used when recording)."""
        pos = car.pos
        best_i, best_d = None, np.inf
        for i, h in enumerate(self.horizontals.horizontals):
            vec = h[1] - h[0]
            t = np.dot(pos - h[0], vec) / np.dot(vec, vec)
            if -0.2 <= t <= 1.2:
                d = np.linalg.norm(pos - (h[0] + t * vec))
                if d < best_d:
                    best_i, best_d = i, d
        if best_i is None:
            return np.array([0.0, 0.0, 0.0, np.linalg.norm(car.vel)])
        h = self.horizontals.horizontals[best_i]
        angle = angle_bw(np.array([-car.orient[1], car.orient[0]]), h[1] - h[0])
        return np.array([float(best_i), 0.5, angle, np.linalg.norm(car.vel)])
