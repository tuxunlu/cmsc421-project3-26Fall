"""
Simulator representing the world with a racetrack and two cars

DO NOT EDIT THIS FILE!
"""

import numpy as np
from car import Car
from particle_filter import ParticleFilter
from kalman_filter import KalmanFilter
from utils import angle_bw
from racetrack import load_racetrack

WORLD_WIDTH = 1400
WORLD_HEIGHT = 800
CAR_LENGTH = 40
CAR_WIDTH = 20
CAR2_DELAY = 40          # in the replay, car 2 drives the recorded lap this many frames behind car 1


class Simulator:
    def __init__(self, max_sensor_range=50, sensor_std=0.0, num_particles=50, gps_noise_var=10.0, gps_noise_width=20,
                 sensor_noise_dist="gaussian", sensor_noise_bound=5.0, sensor_fail_prob=0.0,
                 assumed_noise_dist="gaussian", assumed_noise_std=10.0, assumed_noise_bound=5.0,
                 assumed_fail_prob=0.0, assumed_gps_var=None, assumed_gps_width=None):
        """
        max_sensor_range, sensor_std, sensor_noise_dist, sensor_noise_bound, sensor_fail_prob:
            the cars' real range sensors
        assumed_noise_dist, assumed_noise_std, assumed_noise_bound, assumed_fail_prob:
            the sensor model that the particle filters assume
        gps_noise_var, gps_noise_width: the cars' real GPS noise (Gaussian variance, uniform width)
        assumed_gps_var, assumed_gps_width: the GPS noise that the Kalman filters assume (None: the real value)
        """
        self.racetrack = load_racetrack("data/racetrack.npz")
        car_args = dict(max_sensor_range=max_sensor_range, sensor_std=sensor_std, gps_noise_var=gps_noise_var,
                        gps_noise_width=gps_noise_width, sensor_noise_dist=sensor_noise_dist,
                        sensor_noise_bound=sensor_noise_bound, sensor_fail_prob=sensor_fail_prob)
        self.car1 = Car(**car_args)
        self.car2 = Car(**car_args)

        # Set different initial positions for car1 and car2
        self.car1.pos = np.array([750.0, 760.0])
        self.car2.pos = np.array([750.0, 730.0])

        self.max_sensor_range = max_sensor_range
        self.sensor_std = sensor_std
        self.num_particles = num_particles
        self.sensor_model = dict(noise_dist=assumed_noise_dist, noise_std=assumed_noise_std,
                                 noise_bound=assumed_noise_bound, fail_prob=assumed_fail_prob)
        self.do_particle_filtering = False
        self.particle_filter1 = None
        self.particle_filter2 = None
        self.x_est1 = self.y_est1 = self.orient_est1 = None
        self.x_est2 = self.y_est2 = self.orient_est2 = None

        self.do_kalman_filtering = False
        self.kalman_filter1 = None
        self.kalman_filter2 = None
        self.kf_state1 = None
        self.kf_state2 = None
        self.gps_measurement1 = self.gps_measurement2 = None
        self.gps_noise_var = gps_noise_var
        self.gps_noise_width = gps_noise_width
        self.assumed_gps_var = gps_noise_var if assumed_gps_var is None else assumed_gps_var
        self.assumed_gps_width = gps_noise_width if assumed_gps_width is None else assumed_gps_width
        self.gps_noise_dist = "gaussian"

        self.lap_data_old = np.load("data/lap_data.npy")
        self.cur_i = 2
        self.replaying = False

        self.checkpoints = self.racetrack.checkpoints
        self.car1_next_checkpoint = 0
        self.car2_next_checkpoint = 0
        self.car1_checkpoint_reached = []
        self.car2_checkpoint_reached = []
        self.car1_laps = 0
        self.car2_laps = 0
        self.car1_errors = []          # position error of the estimate of car 1 at every step
        self.car2_errors = []

        self.game_over = False
        self.winner = None

    def get_car_corners(self, car):
        half_length = CAR_LENGTH / 2
        half_width = CAR_WIDTH / 2
        cos_theta = car.orient[0]
        sin_theta = car.orient[1]
        corners = np.array([[-half_length, -half_width], [half_length, -half_width],
                            [half_length, half_width], [-half_length, half_width]])
        rotation_matrix = np.array([[cos_theta, -sin_theta], [sin_theta, cos_theta]])
        return np.dot(corners, rotation_matrix.T) + car.pos

    def rectangles_collide(self, corners1, corners2):
        for shape in [corners1, corners2]:
            for i in range(len(shape)):
                axis = np.array([-shape[i - 1][1] + shape[i][1], shape[i - 1][0] - shape[i][0]])
                axis /= np.linalg.norm(axis)
                p1 = corners1 @ axis
                p2 = corners2 @ axis
                if p1.max() < p2.min() or p2.max() < p1.min():
                    return False
        return True

    def check_collision(self):
        """Bounce the two cars off each other when they touch (manual driving only)."""
        if not self.rectangles_collide(self.get_car_corners(self.car1), self.get_car_corners(self.car2)):
            return
        normal = self.car2.pos - self.car1.pos
        norm = np.linalg.norm(normal)
        normal = normal / norm if norm > 1e-10 else np.array([1.0, 0.0])
        impulse = 2 * np.dot(self.car2.vel - self.car1.vel, normal) * normal
        self.car1.vel = 0.8 * (self.car1.vel + impulse / 2)
        self.car2.vel = 0.8 * (self.car2.vel - impulse / 2)
        self.car1.old_vel = self.car1.vel
        self.car2.old_vel = self.car2.vel

    def update_race_progress(self):
        for i, car in enumerate([self.car1, self.car2]):
            nxt = self.car1_next_checkpoint if i == 0 else self.car2_next_checkpoint
            if np.linalg.norm(car.pos - np.array(self.checkpoints[nxt])) < 30:
                nxt = (nxt + 1) % len(self.checkpoints)
                if i == 0:
                    self.car1_checkpoint_reached.append(car.pos.copy())
                    self.car1_next_checkpoint = nxt
                    self.car1_laps += nxt == 0
                else:
                    self.car2_checkpoint_reached.append(car.pos.copy())
                    self.car2_next_checkpoint = nxt
                    self.car2_laps += nxt == 0
        for i, laps in ((1, self.car1_laps), (2, self.car2_laps)):
            if laps >= 3 and not self.game_over:
                self.game_over, self.winner = True, "Car {}".format(i)

    def record_errors(self):
        if self.do_particle_filtering:
            self.car1_errors.append(float(np.linalg.norm(self.car1.pos - np.array([self.x_est1, self.y_est1]))))
            self.car2_errors.append(float(np.linalg.norm(self.car2.pos - np.array([self.x_est2, self.y_est2]))))
        elif self.do_kalman_filtering:
            self.car1_errors.append(float(np.linalg.norm(self.car1.pos - np.ravel(self.kf_state1)[:2])))
            self.car2_errors.append(float(np.linalg.norm(self.car2.pos - np.ravel(self.kf_state2)[:2])))

    def init_particles(self):
        self.do_particle_filtering = True
        self.particle_filter1 = ParticleFilter(self.num_particles, 0, WORLD_WIDTH, 0, WORLD_HEIGHT, **self.sensor_model)
        self.particle_filter2 = ParticleFilter(self.num_particles, 0, WORLD_WIDTH, 0, WORLD_HEIGHT, **self.sensor_model)

    def stop_particles(self):
        self.do_particle_filtering = False
        self.particle_filter1 = None
        self.particle_filter2 = None

    def init_kalman(self):
        self.do_kalman_filtering = True
        self.kalman_filter1 = KalmanFilter(self.car1, self.assumed_gps_var, self.assumed_gps_width)
        self.kalman_filter2 = KalmanFilter(self.car2, self.assumed_gps_var, self.assumed_gps_width)

    def stop_kalman(self):
        self.do_kalman_filtering = False
        self.kalman_filter1 = self.kalman_filter2 = None

    def toggle_particles(self):
        if self.do_particle_filtering:
            self.stop_particles()
        else:
            self.init_particles()

    def toggle_kalman(self):
        if self.do_kalman_filtering:
            self.stop_kalman()
        else:
            self.init_kalman()

    def toggle_gps_noise_dist(self):
        self.gps_noise_dist = "uniform" if self.gps_noise_dist == "gaussian" else "gaussian"

    def toggle_replay(self):
        self.replaying = not self.replaying

    def _replay_pose(self, car, i):
        """Put a car at frame i of the recorded lap (frames before 0 = waiting at the start)."""
        lap = self.lap_data_old
        cur, prev, prev2 = lap[max(i, 0)], lap[max(i - 2, 0)], lap[max(i - 4, 0)]
        car.pos = cur[0:2].copy()
        car.orient = cur[2:].copy()
        car.vel = cur[0:2] - prev[0:2]
        car.old_vel = prev[0:2] - prev2[0:2]

    def loop(self):
        """Advance the simulation by one step.  Returns False when the replay or the race is over."""
        if self.replaying:
            if self.cur_i >= len(self.lap_data_old) - 1:
                return False
            self._replay_pose(self.car1, self.cur_i)
            self._replay_pose(self.car2, self.cur_i - CAR2_DELAY)
            self.cur_i += 2
        else:
            self.car1.update(self.racetrack.contour_inner, self.racetrack.contour_outer)
            self.car2.update(self.racetrack.contour_inner, self.racetrack.contour_outer)
            self.check_collision()

        d_orient1 = angle_bw(self.car1.vel, self.car1.old_vel) * np.pi / 180.0
        d_orient2 = angle_bw(self.car2.vel, self.car2.old_vel) * np.pi / 180.0

        self.car1.measure_sensor_dists(self.racetrack)
        self.car2.measure_sensor_dists(self.racetrack)

        if self.do_particle_filtering:
            sensor = self.racetrack.read_distances
            speed1 = np.linalg.norm(self.car1.vel)
            speed2 = np.linalg.norm(self.car2.vel)
            self.x_est1, self.y_est1, self.orient_est1 = self.particle_filter1.filtering_and_estimation(
                sensor, self.max_sensor_range, self.car1.sensor_dists, d_orient1, speed1)
            self.x_est2, self.y_est2, self.orient_est2 = self.particle_filter2.filtering_and_estimation(
                sensor, self.max_sensor_range, self.car2.sensor_dists, d_orient2, speed2)

        if self.do_kalman_filtering:
            self.gps_measurement1 = self.car1.measure_gps(noise_dist=self.gps_noise_dist)
            self.kf_state1 = self.kalman_filter1.predict_and_update(self.gps_measurement1, self.gps_noise_dist)
            self.gps_measurement2 = self.car2.measure_gps(noise_dist=self.gps_noise_dist)
            self.kf_state2 = self.kalman_filter2.predict_and_update(self.gps_measurement2, self.gps_noise_dist)

        self.record_errors()
        self.update_race_progress()
        return not self.game_over
