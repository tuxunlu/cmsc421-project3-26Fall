import math
import numpy as np


def length(x):
    return math.sqrt(x[0] ** 2 + x[1] ** 2)


def angle_bw(x, y):
    """Signed angle in degrees from vector y to vector x (clockwise positive on the screen,
    where the y axis points down)."""
    normx = np.linalg.norm(x)
    normy = np.linalg.norm(y)
    if normx <= 1e-8 or normy <= 1e-8:
        return 0
    x = x / normx
    y = y / normy
    return -math.degrees(math.asin(max(-1.0, min(1.0, x[0] * y[1] - x[1] * y[0]))))


def add_noise(x, std):
    return x + np.random.normal(0, std)
